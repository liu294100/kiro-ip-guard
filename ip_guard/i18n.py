def effective_language(language: str | None) -> str:
    value = str(language or "auto").strip()
    if value == "zh_CN":
        value = "zh-CN"
    if value != "auto":
        return value if value in {"zh-CN", "en"} else "en"
    system_language = (locale.getlocale()[0] or "").strip().lower()
    # Windows commonly returns names such as "Chinese (Simplified)_China"
    # instead of a BCP 47 language tag such as "zh-CN".
    return "zh-CN" if system_language.startswith(("zh", "chinese")) else "en"


def translate(language: str | None, text: str, **values: object) -> str:
    template = EN_TRANSLATIONS.get(text, text) if effective_language(language) == "en" else text
    return template.format(**values) if values else template
